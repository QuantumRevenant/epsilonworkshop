    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed
        String username = jTextFieldUsername.getText().trim();
        char[] passwordChars = jPasswordFieldPassword.getPassword();

        jLabelError.setText(" ");

        try {
            new AuthController().login(username, new String(passwordChars));
            new MainFrame().setVisible(true);
            dispose();

        } catch (AuthenticationException e) {
            jLabelError.setText("Usuario o contraseña incorrectos");
        } catch (SQLException e) {
            jLabelError.setText("No se pudo conectar con la base de datos");
        } catch (IllegalStateException e) {
            jLabelError.setText("Error de configuración de la cuenta");
        } finally {
            Arrays.fill(passwordChars, '0');
        }
    }//GEN-LAST:event_jButtonLoginActionPerformed

